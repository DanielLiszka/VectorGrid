    side_results = {
        "long": train_side("long", context, deps, bundle_dir),
        "short": train_side("short", context, deps, bundle_dir),
    }
    calibration = write_calibration(bundle_dir, side_results, context["config"])
    metrics = {
        "version": 1,
        "bundle_id": bundle_id,
        "generated_at_utc": created_at_utc,
        "score_contract": context["config"].get("score_contract", {}),
        "thresholds": [float(value) for value in context["config"].get("metrics", {}).get("thresholds", [])],
        "long": {
            "counts": side_results["long"]["counts"],
            "best_iteration": side_results["long"]["best_iteration"],
            "tree_count": side_results["long"]["tree_count"],
            "metrics": side_results["long"]["metrics"],
        },
        "short": {
            "counts": side_results["short"]["counts"],
            "best_iteration": side_results["short"]["best_iteration"],
            "tree_count": side_results["short"]["tree_count"],
            "metrics": side_results["short"]["metrics"],
        },
        "training_windows_summary": build_training_windows_summary(context),
    }
    write_json(bundle_dir / "metrics.json", metrics)
    hashes = {
        **sidecar_hashes,
        "source_dataset_csv": sha256_file(dataset_csv),
        "source_feature_schema_json": sha256_file(feature_schema_path),
        "source_split_manifest_json": sha256_file(split_manifest_path),
        "source_training_config_json": sha256_file(training_config_path),
        "training_config.json": sha256_file(bundle_dir / "training_config.json"),
        "model_long.cbm": sha256_file(bundle_dir / "model_long.cbm"),
        "model_short.cbm": sha256_file(bundle_dir / "model_short.cbm"),
        "feature_importance_long.csv": sha256_file(bundle_dir / "feature_importance_long.csv"),
        "feature_importance_short.csv": sha256_file(bundle_dir / "feature_importance_short.csv"),
        "metrics.json": sha256_file(bundle_dir / "metrics.json"),
    }
    if calibration is not None:
        hashes["calibration.json"] = sha256_file(bundle_dir / "calibration.json")
    manifest = build_manifest(
        bundle_id,
        context,
        side_results,
        calibration,
        hashes,
        hashes["training_config.json"],
        hashes["metrics.json"],
        created_at_utc,
        deps,
        repo_root,
    )
    write_json(bundle_dir / "manifest.json", manifest)
    hashes["manifest.json"] = sha256_file(bundle_dir / "manifest.json")
    provenance = {
        "version": 1,
        "bundle_id": bundle_id,
        "generated_at_utc": created_at_utc,
        "script_version": SCRIPT_VERSION,
        "sha256": hashes,
        "git": git_metadata(repo_root),
        "package_versions": package_versions(context["np"], context["pd"], deps),
    }
    write_json(bundle_dir / "provenance.json", provenance)
    return {
        "dry_run": False,
        "bundle_id": bundle_id,
        "bundle_dir": str(bundle_dir),
        "manifest": str(bundle_dir / "manifest.json"),
        "metrics": str(bundle_dir / "metrics.json"),
        "provenance": str(bundle_dir / "provenance.json"),
    }


