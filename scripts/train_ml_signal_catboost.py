def normalize_probability(value: float) -> float:
    if not math.isfinite(value):
        return 0.5
    return min(max(value, 1.0e-6), 1.0 - 1.0e-6)


def sigmoid(raw: Any, np: Any) -> Any:
    clipped = np.clip(raw, -40.0, 40.0)
    return np.clip(1.0 / (1.0 + np.exp(-clipped)), 1.0e-6, 1.0 - 1.0e-6)


def scalar_or_none(value: Any) -> Optional[float]:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    return number if math.isfinite(number) else None


def int_or_none(value: Any) -> Optional[int]:
    try:
        if value is None:
            return None
        number = int(value)
    except (TypeError, ValueError):
        return None
    return number


def clean_optional_text(value: Any) -> Optional[str]:
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def validate_config(config: dict[str, Any]) -> None:
    if int_or_none(config.get("version")) != 1:
        raise UserFacingError("training config version must be 1.")
    seed = int_or_none(config.get("seed"))
    if seed is None:
        raise UserFacingError("training config requires integer 'seed'.")
    thresholds = config.get("metrics", {}).get("thresholds", [])
    if not isinstance(thresholds, list) or not thresholds:
        raise UserFacingError("training config metrics.thresholds must be a non-empty list.")
    bad = [value for value in thresholds if scalar_or_none(value) is None]
    if bad:
        raise UserFacingError(f"training config metrics.thresholds contains non-numeric values: {bad}")
    calibration = config.get("calibration", {})
    method = str(calibration.get("method", "sigmoid")).strip().lower()
    if bool(calibration.get("enabled", False)) and method not in {"sigmoid", "isotonic"}:
        raise UserFacingError(
            "training config calibration.method must be 'sigmoid' or 'isotonic' when enabled."
        )


def validate_schema(schema: dict[str, Any]) -> list[str]:
    if schema.get("strategy_kind") not in (None, "MlSignal"):
        raise UserFacingError(
            f"feature schema strategy_kind must be 'MlSignal', got {schema.get('strategy_kind')!r}."
        )
    feature_names = schema.get("feature_names")
    if not isinstance(feature_names, list) or not feature_names:
        raise UserFacingError("feature schema must contain a non-empty feature_names list.")
    out: list[str] = []
    seen: set[str] = set()
    for raw in feature_names:
        name = str(raw).strip()
        if not name:
            raise UserFacingError("feature schema contains an empty feature name.")
        if name in seen:
            raise UserFacingError(f"feature schema contains duplicate feature name '{name}'.")
        seen.add(name)
        out.append(name)
    return out


def validate_split_manifest(split_manifest: dict[str, Any]) -> list[dict[str, Any]]:
    windows = split_manifest.get("windows")
    if not isinstance(windows, list) or not windows:
        raise UserFacingError("split manifest must contain a non-empty windows list.")
    normalized: list[dict[str, Any]] = []
    seen: set[str] = set()
    required = [
        "split_id",
        "train_start",
        "train_end",
        "calibration_start",
        "calibration_end",
        "test_start",
        "test_end",
    ]
    for index, window in enumerate(windows):
        if not isinstance(window, dict):
            raise UserFacingError(f"split window {index} must be an object.")
        missing = [key for key in required if key not in window]
        if missing:
            raise UserFacingError(f"split window {index} is missing fields: {', '.join(missing)}")
        split_id = str(window["split_id"]).strip()
        if not split_id:
            raise UserFacingError(f"split window {index} has an empty split_id.")
        if split_id in seen:
            raise UserFacingError(f"split manifest contains duplicate split_id '{split_id}'.")
        seen.add(split_id)
        parsed = {"split_id": split_id}
        for key in required[1:]:
            value = int_or_none(window.get(key))
            if value is None or value < 0:
                raise UserFacingError(f"split window '{split_id}' field {key} must be >= 0.")
            parsed[key] = value
        if not (
            parsed["train_start"]
            <= parsed["train_end"]
            <= parsed["calibration_start"]
            <= parsed["calibration_end"]
            <= parsed["test_start"]
            <= parsed["test_end"]
        ):
            raise UserFacingError(f"split window '{split_id}' has invalid ordered bounds.")
        normalized.append(parsed)
    return normalized


def read_dataset(dataset_csv: Path, pd: Any) -> Any:
    try:
        return pd.read_csv(dataset_csv)
    except Exception as exc:
        raise UserFacingError(f"failed to read dataset CSV '{dataset_csv}': {exc}") from exc


def validate_dataset_columns(df: Any, feature_names: list[str], config: dict[str, Any]) -> None:
    required = ["timestamp", "ticker_id", "split_id"]
    if bool(config.get("sample_weight", {}).get("enabled", False)):
        required.append(str(config.get("sample_weight", {}).get("column", "sample_weight")))
    for side in ("long", "short"):
        side_cfg = config.get("labels", {}).get(side, {})
        required.append(str(side_cfg.get("label_column", f"y_{side}")))
        if bool(side_cfg.get("use_keep_filter", True)):
            required.append(str(side_cfg.get("keep_column", f"keep_{side}")))
    missing = [column for column in required + feature_names if column not in df.columns]
    if missing:
        raise UserFacingError(f"dataset CSV is missing required columns: {', '.join(missing)}")
    if len(df.index) == 0:
        raise UserFacingError("dataset CSV contains no rows.")


def assign_split_roles(
    df: Any,
    schema: dict[str, Any],
    windows: list[dict[str, Any]],
    np: Any,
) -> tuple[Any, dict[str, Any]]:
    first_valid_bar = int_or_none(schema.get("first_valid_bar")) or 0
    split_by_id = {window["split_id"]: window for window in windows}
    fallback_windows = sorted(windows, key=lambda value: (value["train_start"], value["split_id"]))
    roles: list[str] = []
    split_ids = df["split_id"].fillna("").astype(str).tolist()
    missing_split_ids: set[str] = set()
    fallback_assignments = 0
    unassigned = 0
    for row_index, split_id in enumerate(split_ids):
        bar_index = first_valid_bar + row_index
        window = split_by_id.get(split_id.strip()) if split_id.strip() else None
        if split_id.strip() and window is None:
            missing_split_ids.add(split_id.strip())
        if window is None:
            for candidate in fallback_windows:
                if candidate["train_start"] <= bar_index < candidate["test_end"]:
                    window = candidate
                    fallback_assignments += 1
                    break
        role = "none"
        if window is None:
            unassigned += 1
        elif window["train_start"] <= bar_index < window["train_end"]:
            role = "train"
        elif window["calibration_start"] <= bar_index < window["calibration_end"]:
            role = "calibration"
        elif window["test_start"] <= bar_index < window["test_end"]:
            role = "test"
        roles.append(role)
    role_array = np.array(roles, dtype=object)
    summary = {
        "assignment": "csv_split_id_first_match",
        "first_valid_bar": first_valid_bar,
        "split_window_count": len(windows),
        "role_counts": {role: int((role_array == role).sum()) for role in ["train", "calibration", "test", "none"]},
        "fallback_assignments": int(fallback_assignments),
        "unassigned_rows": int(unassigned),
        "missing_split_ids": sorted(missing_split_ids),
    }
    if missing_split_ids:
        raise UserFacingError(
            "dataset CSV references split_id values that are not in the split manifest: "
            + ", ".join(sorted(missing_split_ids))
        )
    return role_array, summary


def numeric_matrix(df: Any, feature_names: list[str], np: Any, pd: Any) -> Any:
    frame = df.loc[:, feature_names].apply(pd.to_numeric, errors="coerce")
    return frame.replace([np.inf, -np.inf], np.nan).astype("float32")


def side_masks(
    df: Any,
    roles: Any,
    side: str,
    config: dict[str, Any],
    np: Any,
    pd: Any,
) -> dict[str, Any]:
    side_cfg = config.get("labels", {}).get(side, {})
    label_column = str(side_cfg.get("label_column", f"y_{side}"))
    keep_column = str(side_cfg.get("keep_column", f"keep_{side}"))
    y = df[label_column].apply(pd.to_numeric, errors="coerce")
    eligible = y.notna().to_numpy()
    if bool(side_cfg.get("use_keep_filter", True)):
        keep = df[keep_column].apply(pd.to_numeric, errors="coerce").fillna(0)
        eligible = eligible & (keep.to_numpy(dtype=float) > 0.0)
    masks = {
        "train": (roles == "train") & eligible,
        "calibration": (roles == "calibration") & eligible,
        "test": (roles == "test") & eligible,
    }
    labels = y.fillna(0).astype(int).to_numpy()
    counts = {}
    for role, mask in masks.items():
        values = labels[mask]
        counts[role] = {
            "rows": int(mask.sum()),
            "positive": int((values == 1).sum()),
            "negative": int((values == 0).sum()),
        }
    return {
        "label_column": label_column,
        "keep_column": keep_column,
        "labels": labels,
        "masks": masks,
        "counts": counts,
    }


def validate_side_counts(side: str, side_info: dict[str, Any], config: dict[str, Any]) -> None:
    split_policy = config.get("split_policy", {})
    minimum = split_policy.get("minimum_rows", {})
    for role in ("train", "calibration", "test"):
        required_flag = bool(split_policy.get(f"require_{role}_rows", True))
        min_rows = int_or_none(minimum.get(role)) or 0
        rows = side_info["counts"][role]["rows"]
        if required_flag and rows < max(1, min_rows):
            raise UserFacingError(
                f"{side} side has {rows} eligible {role} rows; "
                f"requires at least {max(1, min_rows)}."
            )
    train_counts = side_info["counts"]["train"]
    if train_counts["positive"] == 0 or train_counts["negative"] == 0:
        raise UserFacingError(
            f"{side} training rows must contain both classes; got "
            f"{train_counts['positive']} positive and {train_counts['negative']} negative."
        )
    calibration_cfg = config.get("calibration", {})
    if bool(calibration_cfg.get("enabled", False)) and bool(calibration_cfg.get("required", True)):
        calibration_counts = side_info["counts"]["calibration"]
        if calibration_counts["positive"] == 0 or calibration_counts["negative"] == 0:
            raise UserFacingError(
                f"{side} calibration rows must contain both classes because calibration is required; got "
                f"{calibration_counts['positive']} positive and {calibration_counts['negative']} negative."
            )


def role_timestamp_ranges(df: Any, roles: Any, np: Any, pd: Any) -> dict[str, Any]:
    timestamps = df["timestamp"].apply(pd.to_numeric, errors="coerce").to_numpy()
    ranges: dict[str, Any] = {}
    for role in ("train", "calibration", "test"):
        mask = roles == role
        values = timestamps[mask]
        values = values[~np.isnan(values)]
        ranges[role] = {
            "first_timestamp": int(values[0]) if len(values) else None,
            "last_timestamp": int(values[-1]) if len(values) else None,
        }
    return ranges


def prepare_context(
    dataset_csv: Path,
    feature_schema_path: Path,
    split_manifest_path: Path,
    training_config_path: Path,
    export_manifest_path: Optional[Path],
) -> dict[str, Any]:
    np, pd = import_frame_dependencies()
    config_raw = load_json(training_config_path, "training config")
    config = deep_merge(DEFAULT_CONFIG, config_raw)
    validate_config(config)
    schema = load_json(feature_schema_path, "feature schema")
    split_manifest = load_json(split_manifest_path, "split manifest")
    feature_names = validate_schema(schema)
    windows = validate_split_manifest(split_manifest)
    df = read_dataset(dataset_csv, pd)
    validate_dataset_columns(df, feature_names, config)
    roles, split_summary = assign_split_roles(df, schema, windows, np)
    side_info = {
        "long": side_masks(df, roles, "long", config, np, pd),
        "short": side_masks(df, roles, "short", config, np, pd),
    }
    for side, info in side_info.items():
        validate_side_counts(side, info, config)
    X = numeric_matrix(df, feature_names, np, pd)
    sample_weight = None
    sample_weight_column = str(config.get("sample_weight", {}).get("column", "sample_weight"))
    if bool(config.get("sample_weight", {}).get("enabled", False)):
        sample_weight = (
            df[sample_weight_column]
            .apply(pd.to_numeric, errors="coerce")
            .fillna(1.0)
            .astype("float32")
            .to_numpy()
        )
    source_export_manifest = (
        load_json(export_manifest_path, "source export manifest") if export_manifest_path else None
    )
    return {
        "np": np,
        "pd": pd,
        "config": config,
        "schema": schema,
        "split_manifest": split_manifest,
        "windows": windows,
        "feature_names": feature_names,
        "df": df,
        "X": X,
        "sample_weight": sample_weight,
        "roles": roles,
        "split_summary": split_summary,
        "side_info": side_info,
        "source_export_manifest": source_export_manifest,
    }


def package_versions(np: Any, pd: Any, deps: Optional[dict[str, Any]] = None) -> dict[str, str]:
    versions = {
        "python": platform.python_version(),
        "numpy": getattr(np, "__version__", "unknown"),
        "pandas": getattr(pd, "__version__", "unknown"),
    }
    if deps is not None:
        versions["catboost"] = getattr(sys.modules.get("catboost"), "__version__", "unknown")
        versions["scikit_learn"] = getattr(deps["sklearn"], "__version__", "unknown")
    return versions


def git_metadata(repo_root: Path) -> dict[str, Any]:
    def run_git(*args: str) -> Optional[str]:
        try:
            completed = subprocess.run(
                ["git", *args],
                cwd=repo_root,
                check=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
                text=True,
            )
            return completed.stdout.strip()
        except Exception:
            return None

    status = run_git("status", "--short")
    return {
        "commit": run_git("rev-parse", "HEAD"),
        "branch": run_git("rev-parse", "--abbrev-ref", "HEAD"),
        "dirty": bool(status),
    }


def resolved_created_at(config: dict[str, Any]) -> str:
    configured = clean_optional_text(config.get("bundle", {}).get("created_at_utc"))
    if configured:
        return configured
    source_date_epoch = clean_optional_text(os.environ.get("SOURCE_DATE_EPOCH"))
    if source_date_epoch:
        try:
            return datetime.fromtimestamp(int(source_date_epoch), timezone.utc).isoformat().replace(
                "+00:00", "Z"
            )
        except ValueError:
            pass
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def model_params_for_side(config: dict[str, Any], side: str) -> dict[str, Any]:
    catboost_cfg = config.get("catboost", {})
    params = deepcopy(catboost_cfg.get("params", {}))
    params.update(deepcopy(catboost_cfg.get(f"{side}_params", {})))
    params["random_seed"] = int(config["seed"])
    class_balance = config.get("class_balance", {})
    auto_class_weights = class_balance.get("auto_class_weights")
    if auto_class_weights is not None and str(auto_class_weights).strip():
        params.setdefault("auto_class_weights", auto_class_weights)
    return {key: value for key, value in params.items() if value is not None}


def make_pool(
    Pool: Any,
    X: Any,
    y: Any,
    mask: Any,
    feature_names: list[str],
    sample_weight: Any,
) -> Any:
    weight = sample_weight[mask] if sample_weight is not None else None
    return Pool(X.loc[mask, :], label=y[mask], weight=weight, feature_names=feature_names)


def predict_raw(model: Any, pool: Any, np: Any) -> Any:
    raw = model.predict(pool, prediction_type="RawFormulaVal")
    return np.asarray(raw, dtype=float).reshape(-1)


def precision_recall_at_thresholds(y_true: Any, probability: Any, thresholds: list[float]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for threshold in thresholds:
        predicted = probability >= threshold
        positive = y_true == 1
        tp = int((predicted & positive).sum())
        fp = int((predicted & ~positive).sum())
        fn = int((~predicted & positive).sum())
        precision = tp / (tp + fp) if (tp + fp) else None
        recall = tp / (tp + fn) if (tp + fn) else None
        out.append(
            {
                "threshold": float(threshold),
                "precision": precision,
                "recall": recall,
                "predicted_positive": int(predicted.sum()),
                "true_positive": tp,
                "false_positive": fp,
                "false_negative": fn,
            }
        )
    return out


def metric_block(
    y_true: Any,
    probability: Any,
    thresholds: list[float],
    deps: dict[str, Any],
    calibration_bins: int,
    np: Any,
) -> dict[str, Any]:
    probability = np.asarray([normalize_probability(float(value)) for value in probability])
    y_true = np.asarray(y_true, dtype=int)
    positives = int((y_true == 1).sum())
    negatives = int((y_true == 0).sum())
    result: dict[str, Any] = {
        "rows": int(len(y_true)),
        "positive": positives,
        "negative": negatives,
        "auc": None,
        "brier": None,
        "log_loss": None,
        "precision_recall": precision_recall_at_thresholds(y_true, probability, thresholds),
    }
    if len(y_true) == 0:
        return result
    result["brier"] = float(deps["brier_score_loss"](y_true, probability))
    result["log_loss"] = float(deps["log_loss"](y_true, probability, labels=[0, 1]))
    if positives > 0 and negatives > 0:
        result["auc"] = float(deps["roc_auc_score"](y_true, probability))
        bins = max(2, min(int(calibration_bins), len(y_true)))
        prob_true, prob_pred = deps["calibration_curve"](
            y_true, probability, n_bins=bins, strategy="uniform"
        )
        result["calibration_curve"] = [
            {"predicted": float(pred), "observed": float(obs)}
            for pred, obs in zip(prob_pred, prob_true)
        ]
    return result


def fit_calibrator(
    side: str,
    raw: Any,
    y_true: Any,
    config: dict[str, Any],
    deps: dict[str, Any],
    np: Any,
) -> tuple[dict[str, Any], Any]:
    calibration_cfg = config.get("calibration", {})
    method = str(calibration_cfg.get("method", "sigmoid")).strip().lower()
    raw = np.asarray(raw, dtype=float).reshape(-1)
    y_true = np.asarray(y_true, dtype=int)
    if len(set(y_true.tolist())) < 2:
        raise UserFacingError(f"{side} calibration requires both classes.")
    before = sigmoid(raw, np)
    if method == "sigmoid":
        sigmoid_cfg = calibration_cfg.get("sigmoid", {})
        model = deps["LogisticRegression"](
            solver=str(sigmoid_cfg.get("solver", "lbfgs")),
            max_iter=int(sigmoid_cfg.get("max_iter", 1000)),
            random_state=int(config["seed"]),
        )
        model.fit(raw.reshape(-1, 1), y_true)
        coef = float(model.coef_[0][0])
        intercept = float(model.intercept_[0])

        def apply(values: Any) -> Any:
            return sigmoid((np.asarray(values, dtype=float) * coef) + intercept, np)

        after = apply(raw)
        artifact = {
            "method": "sigmoid",
            "coef": coef,
            "intercept": intercept,
        }
    elif method == "isotonic":
        isotonic_cfg = calibration_cfg.get("isotonic", {})
        model = deps["IsotonicRegression"](out_of_bounds=str(isotonic_cfg.get("out_of_bounds", "clip")))
        model.fit(raw, y_true)

        def apply(values: Any) -> Any:
            return np.clip(model.predict(np.asarray(values, dtype=float)), 1.0e-6, 1.0 - 1.0e-6)

        after = apply(raw)
        artifact = {
            "method": "isotonic",
            "x_thresholds": [float(value) for value in model.X_thresholds_],
            "y_thresholds": [float(value) for value in model.y_thresholds_],
        }
    else:
        raise UserFacingError(f"unsupported calibration method '{method}'.")
    artifact.update(
        {
            "source": str(calibration_cfg.get("source", "calibration_windows")),
            "rows": int(len(y_true)),
            "positive": int((y_true == 1).sum()),
            "negative": int((y_true == 0).sum()),
            "brier_before": float(deps["brier_score_loss"](y_true, before)),
            "brier_after": float(deps["brier_score_loss"](y_true, after)),
        }
    )
    return artifact, apply


def write_feature_importance(
    path: Path,
    model: Any,
    train_pool: Any,
    feature_names: list[str],
    pd: Any,
) -> None:
    values = model.get_feature_importance(train_pool, type="FeatureImportance")
    rows = [
        {"feature": feature, "importance": float(importance)}
        for feature, importance in zip(feature_names, values)
    ]
    rows.sort(key=lambda row: (-row["importance"], row["feature"]))
    for index, row in enumerate(rows, start=1):
        row["rank"] = index
    pd.DataFrame(rows, columns=["rank", "feature", "importance"]).to_csv(path, index=False)


def train_side(
    side: str,
    context: dict[str, Any],
    deps: dict[str, Any],
    bundle_dir: Path,
) -> dict[str, Any]:
    np = context["np"]
    config = context["config"]
    side_info = context["side_info"][side]
    masks = side_info["masks"]
    labels = side_info["labels"]
    feature_names = context["feature_names"]
    X = context["X"]
    sample_weight = context["sample_weight"]
    Pool = deps["Pool"]
    CatBoostClassifier = deps["CatBoostClassifier"]

    train_pool = make_pool(Pool, X, labels, masks["train"], feature_names, sample_weight)
    calibration_pool = make_pool(Pool, X, labels, masks["calibration"], feature_names, sample_weight)
    test_pool = make_pool(Pool, X, labels, masks["test"], feature_names, sample_weight)

    params = model_params_for_side(config, side)
    fit_verbose = bool(params.pop("verbose", False))
    model = CatBoostClassifier(**params)
    catboost_cfg = config.get("catboost", {})
    fit_kwargs: dict[str, Any] = {"verbose": fit_verbose}
    if int(catboost_cfg.get("early_stopping_rounds", 0)) > 0:
        fit_kwargs["early_stopping_rounds"] = int(catboost_cfg["early_stopping_rounds"])
    if bool(catboost_cfg.get("use_best_model", True)):
        fit_kwargs["use_best_model"] = True
    model.fit(train_pool, eval_set=calibration_pool, **fit_kwargs)

    model_path = bundle_dir / f"model_{side}.cbm"
    model.save_model(model_path)
    feature_importance_path = bundle_dir / f"feature_importance_{side}.csv"
    write_feature_importance(feature_importance_path, model, train_pool, feature_names, context["pd"])

    raw_by_role = {
        "train": predict_raw(model, train_pool, np),
        "calibration": predict_raw(model, calibration_pool, np),
        "test": predict_raw(model, test_pool, np),
    }
    y_by_role = {
        "train": labels[masks["train"]],
        "calibration": labels[masks["calibration"]],
        "test": labels[masks["test"]],
    }
    raw_probability = {role: sigmoid(raw, np) for role, raw in raw_by_role.items()}
    calibration_artifact = None
    apply_calibration = None
    if bool(config.get("calibration", {}).get("enabled", False)):
        calibration_artifact, apply_calibration = fit_calibrator(
            side, raw_by_role["calibration"], y_by_role["calibration"], config, deps, np
        )
    calibrated_probability = (
        {role: apply_calibration(raw) for role, raw in raw_by_role.items()}
        if apply_calibration is not None
        else raw_probability
    )
    thresholds = [float(value) for value in config.get("metrics", {}).get("thresholds", [0.5])]
    calibration_bins = int(config.get("metrics", {}).get("calibration_curve_bins", 10))
    metrics = {}
    for role in ("train", "calibration", "test"):
        metrics[role] = {
            "raw_probability": metric_block(
                y_by_role[role],
                raw_probability[role],
                thresholds,
                deps,
                calibration_bins,
                np,
            ),
            "calibrated_probability": metric_block(
                y_by_role[role],
                calibrated_probability[role],
                thresholds,
                deps,
                calibration_bins,
                np,
            ),
        }
    return {
        "side": side,
        "model": model,
        "model_path": model_path,
        "feature_importance_path": feature_importance_path,
        "params": {**params, "verbose": fit_verbose},
        "best_iteration": int(model.get_best_iteration() or 0),
        "tree_count": int(getattr(model, "tree_count_", 0) or 0),
        "counts": side_info["counts"],
        "metrics": metrics,
        "calibration": calibration_artifact,
    }


def synthesize_export_manifest(
    context: dict[str, Any],
    dataset_csv: Path,
    source_export_manifest: Optional[dict[str, Any]],
) -> dict[str, Any]:
    schema = context["schema"]
    split_manifest = context["split_manifest"]
    df = context["df"]
    timestamps = df["timestamp"].apply(context["pd"].to_numeric, errors="coerce").dropna()
    base = deepcopy(source_export_manifest) if source_export_manifest else {}
    base.update(
        {
            "version": int(base.get("version", 1) or 1),
            "strategy_kind": "MlSignal",
            "data_id": base.get("data_id")
            or context["config"].get("dataset", {}).get("data_id")
            or inferred_data_id(df),
            "output_path": str(dataset_csv),
            "row_count": int(len(df.index)),
            "feature_schema_path": "feature_schema.json",
            "feature_schema_version": int(schema.get("schema_version", 1) or 1),
            "split_manifest_path": "split_manifest.json",
            "split_count": len(split_manifest.get("windows", [])),
            "horizon_bars": int(schema.get("horizon_bars") or schema.get("label_horizon_bars") or 0),
            "first_valid_bar": int(schema.get("first_valid_bar") or 0),
            "pattern_count": len(schema.get("pattern_ids", [])),
            "feature_count": len(schema.get("feature_names", [])),
            "first_timestamp": int(timestamps.iloc[0]) if len(timestamps) else None,
            "last_timestamp": int(timestamps.iloc[-1]) if len(timestamps) else None,
            "feature_schema_hash": schema.get("schema_hash", ""),
            "exporter_version": schema.get("exporter_version", "unknown"),
        }
    )
    if schema.get("indicator_config") is not None:
        base["indicator_config"] = schema["indicator_config"]
    return base


def inferred_data_id(df: Any) -> str:
    values = [str(value).strip() for value in df["ticker_id"].dropna().unique().tolist()]
    values = [value for value in values if value]
    if len(values) == 1:
        return values[0]
    if not values:
        return "unknown"
    return f"multi_ticker_{len(values)}"


def training_symbol_scope(df: Any, config: dict[str, Any]) -> str:
    configured = clean_optional_text(config.get("dataset", {}).get("symbol_scope"))
    if configured and configured != "from_dataset":
        return configured
    values = [str(value).strip() for value in df["ticker_id"].dropna().unique().tolist()]
    values = [value for value in values if value]
    return values[0] if len(values) == 1 else f"multi_ticker_{len(values)}"


def build_training_windows_summary(context: dict[str, Any]) -> dict[str, Any]:
    np = context["np"]
    summary = deepcopy(context["split_summary"])
    summary["timestamp_ranges"] = role_timestamp_ranges(
        context["df"], context["roles"], np, context["pd"]
    )
    summary["side_counts"] = {
        side: deepcopy(info["counts"]) for side, info in context["side_info"].items()
    }
    split_manifest = context["split_manifest"]
    for key in ("train_bars", "calibration_bars", "test_bars", "gap_bars", "step_bars"):
        if key in split_manifest:
            summary[key] = split_manifest[key]
    return summary


def copy_or_write_sidecars(
    context: dict[str, Any],
    dataset_csv: Path,
    feature_schema_path: Path,
    split_manifest_path: Path,
    source_export_manifest_path: Optional[Path],
    bundle_dir: Path,
) -> dict[str, Any]:
    shutil.copyfile(feature_schema_path, bundle_dir / "feature_schema.json")
    shutil.copyfile(split_manifest_path, bundle_dir / "split_manifest.json")
    export_manifest = synthesize_export_manifest(
        context, dataset_csv, context.get("source_export_manifest")
    )
    write_json(bundle_dir / "export_manifest.json", export_manifest)
    export_manifest_sha256 = sha256_file(bundle_dir / "export_manifest.json")
    return {
        "feature_schema.json": sha256_file(bundle_dir / "feature_schema.json"),
        "split_manifest.json": sha256_file(bundle_dir / "split_manifest.json"),
        "export_manifest.json": export_manifest_sha256,
        "source_export_manifest": sha256_file(source_export_manifest_path)
        if source_export_manifest_path
        else export_manifest_sha256,
    }


def write_calibration(
    bundle_dir: Path, side_results: dict[str, dict[str, Any]], config: dict[str, Any]
) -> Optional[dict[str, Any]]:
    if not bool(config.get("calibration", {}).get("enabled", False)):
        return None
    calibration = {
        "version": 1,
        "calibration_state": "calibrated_probability",
        "source": str(config.get("calibration", {}).get("source", "calibration_windows")),
    }
    for side in ("long", "short"):
        calibration[side] = side_results[side]["calibration"]
    write_json(bundle_dir / "calibration.json", calibration)
    return calibration


