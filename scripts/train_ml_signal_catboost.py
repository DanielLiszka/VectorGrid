def ensure_bundle_dir(bundle_dir: Path, overwrite: bool) -> None:
    if bundle_dir.exists():
        if not bundle_dir.is_dir():
            raise UserFacingError(f"bundle dir '{bundle_dir}' exists but is not a directory.")
        if any(bundle_dir.iterdir()) and not overwrite:
            raise UserFacingError(
                f"bundle dir '{bundle_dir}' is not empty. Pass --overwrite to write into it."
            )
    else:
        bundle_dir.mkdir(parents=True)


def train_bundle(args: argparse.Namespace) -> dict[str, Any]:
    repo_root = Path(__file__).resolve().parents[1]
    dataset_csv = require_file(args.dataset_csv, "dataset CSV")
    feature_schema_path = require_file(args.feature_schema, "feature schema")
    split_manifest_path = require_file(args.split_manifest, "split manifest")
    training_config_path = require_file(args.training_config, "training config")
    source_export_manifest_path = (
        require_file(args.export_manifest, "source export manifest")
        if args.export_manifest
        else infer_source_export_manifest(dataset_csv)
    )
    context = prepare_context(
        dataset_csv,
        feature_schema_path,
        split_manifest_path,
        training_config_path,
        source_export_manifest_path,
    )
