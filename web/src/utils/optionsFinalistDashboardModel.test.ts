describe("optionsFinalistDashboardModel", () => {
  it("builds finalist rows and display-only gate rows from validation artifacts", () => {
    const dashboard = buildOptionsFinalistDashboard(validationFixture());

    expect(dashboard?.verdict).toBe("accepted");
    expect(dashboard?.gates.map((gate) => gate.key)).toEqual([
      "acceptance",
      "coverage",
      "provenance",
      "holdout",
      "stress_lanes",
      "quote_realism",
    ]);
    expect(
      dashboard?.gates.find((gate) => gate.key === "provenance")?.tone,
    ).toBe("pass");
    expect(dashboard?.rows[0]).toMatchObject({
      sourceTupleIndex: 2,
      verdict: "Sealed finalist",
      tone: "pass",
      support: "Supported",
      sourceRobustScore: 0.4,
      validatedRobustScore: 0.44,
      holdoutEv: 0.22,
      stressEv: 0.17,
      strongestStressLabel: "Stress",
      strongestStressEv: 0.17,
      validTrades: 3,
    });
    expect(dashboard?.rows[0]?.drift).toContain("robust +0.040");
  });

  it("handles missing validation artifacts safely", () => {
    expect(buildOptionsFinalistDashboard(null)).toBeNull();
    expect(formatOptionsFinalistNumber(null)).toBe("-");
  });
});
